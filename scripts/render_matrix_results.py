"""Render matrix_sweep.json as 4 tables (one per eval metric) — 9 cells × 5 seeds.

Default mode prints the four metric tables + winner grid to stdout.
With `--md <path>` writes a markdown report (the canonical persisted output)
that the rest of the project reads instead of the bulky JSON.
"""
from __future__ import annotations

import argparse
import json
from pathlib import Path

ATTRS      = ["ov", "qk", "triple"]
INTERVENES = ["ov", "qk", "all"]
METRICS    = [
    ("asr",          "ASR",          "{:>5.3f}",  "{:.3f}"),
    ("delta_logp",   "Δdep-logp",    "{:>+8.3f}", "{:+.3f}"),
    ("delta_ce",     "Δcln-CE",      "{:>+8.4f}", "{:+.4f}"),
    ("delta_gen_ce", "Δgen-CE",      "{:>+8.4f}", "{:+.4f}"),
]


def _winner_label(tup: list, alpha: float) -> str:
    if len(tup) == 1:
        body = f"f{tup[0][0]}({tup[0][1]})"
    else:
        body = ",".join(f"f{x[0]}{x[1]}" for x in tup)
    return f"{body} @ α={alpha:.1f}"


def _eval_baseline(payload: dict) -> dict:
    base = payload["baseline"]
    return base.get("eval", base)  # back-compat with old schema


def _metric(r: dict, key: str) -> float | None:
    """Held-out eval metric for cell r; returns None if missing."""
    e = r.get("eval", r)  # back-compat
    return e.get(key)


def _print_stdout(payload: dict, idx: dict, seeds: list[int]) -> None:
    base = _eval_baseline(payload)
    asr_str = f"{base['asr']:.3f}" if "asr" in base else "n/a"
    print(f"[render] eval baseline: ASR={asr_str}  "
          f"dep_logp={base['dep_logp']:.3f}  clean_CE={base['clean_ce']:.4f}")
    print(f"[render] seeds={seeds}  n_cells={len(ATTRS)*len(INTERVENES)}  (held-out eval split)")

    for key, label, fmt, _ in METRICS:
        print(f"\n## {label}")
        head = f"{'cell':>12}  " + "  ".join(f"{'s'+str(s):>8}" for s in seeds)
        print(head); print("-" * len(head))
        for a in ATTRS:
            for v in INTERVENES:
                row = []
                for s in seeds:
                    r = idx.get((s, a, v))
                    val = _metric(r, key) if r else None
                    row.append(fmt.format(val) if val is not None else f"{'NA':>8}")
                print(f"{a + '×' + v:>12}  " + "  ".join(row))

    print("\n## winner tuple × α (per cell)")
    head = f"{'cell':>12}  " + "  ".join(f"{'s'+str(s):>20}" for s in seeds)
    print(head); print("-" * len(head))
    for a in ATTRS:
        for v in INTERVENES:
            cells = [_winner_label(idx[(s, a, v)]["winner_tuple"],
                                   idx[(s, a, v)]["alpha"]).rjust(20)
                     if (s, a, v) in idx else f"{'NA':>20}" for s in seeds]
            print(f"{a + '×' + v:>12}  " + "  ".join(cells))


def _md_table(seeds: list[int], rows: list[tuple[str, list[str]]]) -> str:
    head = "| cell | " + " | ".join(f"s{s}" for s in seeds) + " |"
    sep  = "|---" * (1 + len(seeds)) + "|"
    body = "\n".join(f"| {name} | " + " | ".join(cells) + " |"
                     for name, cells in rows)
    return "\n".join([head, sep, body])


def _render_md(payload: dict, idx: dict, seeds: list[int]) -> str:
    base = _eval_baseline(payload)
    asr_str = f"**{base['asr']:.3f}**" if "asr" in base else "n/a"
    decoding = payload.get("decoding", {})
    eval_asr = decoding.get("eval_asr", {}) if isinstance(decoding, dict) else {}
    sample_seeds = eval_asr.get("seeds")
    temperature  = eval_asr.get("temperature")
    out: list[str] = []
    out.append("# 9-cell × 5-seed matrix sweep — results")
    out.append("")
    out.append("Auto-generated by `scripts/render_matrix_results.py --md docs/matrix_results.md`. ")
    out.append("Run `./scripts/run_matrix_pipeline.sh` to regenerate.")
    out.append("")
    cfg = payload.get("config", {})
    n_eval = cfg.get("n_eval")
    n_gen_ce = cfg.get("n_gen_ce")
    if isinstance(n_eval, int):
        split_line = (
            f"Each split has {n_eval // 2} deployment + {n_eval // 2} clean "
            f"prompts (`--n_eval {n_eval}`)."
        )
        if isinstance(n_gen_ce, int):
            split_line += f" Δgen-CE uses an `--n_gen_ce {n_gen_ce}` dep subset."
    else:
        split_line = "Each split has 100 deployment + 100 clean prompts."
    out.append("All numbers below are computed on the **held-out eval split** "
               "(disjoint from the selection split that picks the winner per cell). "
               + split_line)
    out.append("")
    if sample_seeds is not None:
        out.append(f"**Eval decoding.** Both generation-using metrics (ASR and "
                   f"Δgen-CE) use pure multinomial sampling at "
                   f"temperature={temperature} (no top_p / top_k truncation), "
                   f"averaged over seeds={list(sample_seeds)} — matches Ketan's "
                   f"1000-prompt eval methodology. The two teacher-forced metrics "
                   f"(Δdep-logp, Δcln-CE) are deterministic. Selection-stage "
                   f"generation (used internally to pick the winner per cell) is "
                   f"greedy and is not reported here. See "
                   f"[[pipeline_matrix#Selection vs eval decoding]] for the rationale.")
        out.append("")
    out.append(f"Eval baseline (no steering): ASR = {asr_str}, "
               f"Δdep-logp = **{base['dep_logp']:.3f}**, "
               f"Δcln-CE = **{base['clean_ce']:.4f}**.")
    out.append("")
    for key, label, _, md_fmt in METRICS:
        out.append(f"## {label}")
        out.append("")
        rows = []
        for a in ATTRS:
            for v in INTERVENES:
                cells = []
                for s in seeds:
                    r = idx.get((s, a, v))
                    val = _metric(r, key) if r else None
                    cells.append(md_fmt.format(val) if val is not None else "NA")
                rows.append((f"{a}×{v}", cells))
        out.append(_md_table(seeds, rows))
        out.append("")
    out.append("## Winner tuple × α (per cell)")
    out.append("")
    out.append("Selected on the selection split; the metric tables above evaluate these on the eval split.")
    out.append("")
    rows = []
    for a in ATTRS:
        for v in INTERVENES:
            cells = [_winner_label(idx[(s, a, v)]["winner_tuple"],
                                   idx[(s, a, v)]["alpha"])
                     if (s, a, v) in idx else "NA" for s in seeds]
            rows.append((f"{a}×{v}", cells))
    out.append(_md_table(seeds, rows))
    out.append("")
    return "\n".join(out)


def main() -> None:
    p = argparse.ArgumentParser()
    p.add_argument("--in", dest="inp", type=Path, required=True,
                   help="path to matrix_sweep.json (e.g. results/matrix_sweep.json)")
    p.add_argument("--md", type=Path, default=None,
                   help="if set, also write a markdown report to this path")
    args = p.parse_args()

    payload = json.loads(args.inp.read_text())
    seeds = sorted({int(r["seed"]) for r in payload["results"]})
    idx: dict = {(int(r["seed"]), r["attr"], r["intervene"]): r
                 for r in payload["results"]}

    _print_stdout(payload, idx, seeds)

    if args.md is not None:
        args.md.parent.mkdir(parents=True, exist_ok=True)
        args.md.write_text(_render_md(payload, idx, seeds))
        print(f"\n[render] wrote {args.md}")


if __name__ == "__main__":
    main()
